"""
Designation Benchmark Matching Schemas
=======================================
Schemas for matching a candidate's resume against curated role profiles.

IMPORTANT DISCLAIMER: Role profiles in this module are curated by the platform
team and represent general market expectations for each designation. They are
NOT sourced from any specific employer's job description. Match scores are
indicative benchmarks, not guarantees of suitability for any particular role.
Actual hiring requirements vary significantly by company, team, and seniority level.
"""

from typing import List, Optional
from pydantic import BaseModel, Field
from app.schemas.job_matching import JobMatchReport


class RoleProfile(BaseModel):
    """
    A versioned, curated specification of market expectations for a given designation.

    Attributes:
        role_id: Unique machine-readable identifier (e.g., "ai_engineer").
        display_name: Human-readable role name (e.g., "AI / ML Engineer").
        version: Profile version string — increment when expectations change.
        description: Short description of what this role typically involves.
        mandatory_skills: Skills that most employers in this role require.
            A candidate missing most of these will score low.
        preferred_skills: Nice-to-have skills that improve match score but are
            not hard requirements.
        minimum_experience_years: Minimum years of relevant experience expected.
        preferred_experience_years: Preferred years for a competitive profile.
        domain_knowledge: Industry/domain expertise that strengthens candidacy.
        education_signals: Degree or field signals that positively indicate fit
            (e.g., "B.Tech Computer Science"). Not a strict filter.
        assumptions: Explicit list of assumptions made when designing this profile,
            so candidates and users understand the benchmark's basis.
    """

    role_id: str = Field(..., description="Machine-readable unique role identifier")
    display_name: str = Field(..., description="Human-readable role display name")
    version: str = Field(default="1.0", description="Profile version")
    description: str = Field(..., description="Short description of role responsibilities")
    mandatory_skills: List[str] = Field(
        default_factory=list,
        description="Skills most employers require for this role"
    )
    preferred_skills: List[str] = Field(
        default_factory=list,
        description="Desirable but not required skills"
    )
    minimum_experience_years: float = Field(
        default=0.0,
        description="Minimum years of relevant experience typically expected"
    )
    preferred_experience_years: float = Field(
        default=2.0,
        description="Preferred years of experience for a competitive profile"
    )
    domain_knowledge: List[str] = Field(
        default_factory=list,
        description="Domain or industry knowledge that strengthens candidacy"
    )
    education_signals: List[str] = Field(
        default_factory=list,
        description="Degree fields that signal fit (not a strict filter)"
    )
    assumptions: List[str] = Field(
        default_factory=list,
        description="Explicit assumptions made when curating this profile"
    )


class DesignationMatchReport(BaseModel):
    """
    Result of matching a resume against a curated designation profile.

    Extends the base JobMatchReport with designation-specific metadata
    and an explicit disclaimer about the curated-profile benchmark approach.

    DISCLAIMER: This report is generated by comparing the candidate's extracted
    resume data against a platform-curated role profile. It is an indicative
    benchmark only. Actual job requirements vary by company, team size, tech stack,
    and seniority level. Do not use this score as the sole basis for career decisions.
    """

    role_id: str = Field(..., description="Role identifier that was matched against")
    role_display_name: str = Field(..., description="Human-readable name of the matched role")
    role_version: str = Field(..., description="Version of the profile used for this match")
    role_description: str = Field(..., description="Short description of what this role involves")

    match_report: JobMatchReport = Field(
        ...,
        description="Full hybrid match result including scores, evidence, and skill gaps"
    )

    assumptions_applied: List[str] = Field(
        default_factory=list,
        description="Assumptions made by the curated profile that influenced this result"
    )

    disclaimer: str = Field(
        default=(
            "This score is based on a platform-curated role profile, not a specific employer's "
            "job description. Market expectations vary by company, team, and seniority level. "
            "Use this score as a directional benchmark to identify skill gaps, not as a "
            "definitive measure of employability."
        ),
        description="Mandatory disclaimer about the curated-profile benchmark approach"
    )


class DesignationListResponse(BaseModel):
    """Response schema for listing available designation profiles."""

    available_designations: List[dict] = Field(
        ...,
        description="List of available role profiles with id, display_name and description"
    )
    total: int = Field(..., description="Total number of available profiles")
    disclaimer: str = Field(
        default=(
            "All role profiles are curated benchmarks representing general market expectations. "
            "They are not sourced from any specific employer's job description."
        )
    )
